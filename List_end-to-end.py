# Definition:-
# A list is an ordered, mutable (changeable), and iterable collection of elements.
# It can store heterogeneous(Different types) data types (integers, strings, floats, objects, etc.).

# Properties:

# Ordered (elements have a fixed order)

# Mutable (you can change elements)

# Duplicates allowed

# Can store mixed data types

# Examples
my_list = [1, "hello", 3.14, True]
print(my_list)

